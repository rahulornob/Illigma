#!/usr/bin/env node
// Turns figma-export.json (the raw read-only export of the Figma file
// "Illigma") into tokens.json (W3C Design Tokens), tokens.css (CSS custom
// properties) and src/index.ts (a typed `tokens` object).
//
// Plain Node, no dependencies. Run with `npm run build:tokens -w @illigma/tokens`.
// `node scripts/build.mjs --check` exits 1 if the committed files are stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PRIMITIVES = "Illigma Primitives";
const SEMANTIC = "Illigma UI";
const MODES = /** @type {const} */ (["dark", "light"]);
const EXT = "app.illigma";

const FONT_WEIGHTS = { Thin: 100, "Extra Light": 200, Light: 300, Regular: 400, Medium: 500, "Semi Bold": 600, Bold: 700, "Extra Bold": 800, Black: 900 };
const FONT_FALLBACKS = { "JetBrains Mono": "ui-monospace, monospace" };
const DEFAULT_FALLBACK = "system-ui, sans-serif";

/** "UI/Body" -> ["ui", "body"]; "Elevation/1 island" -> ["elevation", "1-island"] */
const segments = (name) => name.split("/").map((s) => s.trim().toLowerCase().replace(/\s+/g, "-"));
/** The naming rule: Figma path, lowercased, "/" and spaces become "-". */
export const cssVarName = (name, prefix = "") => `--${prefix}${segments(name).join("-")}`;
const ref = (name) => `{${segments(name).join(".")}}`;

const round = (n, places) => Math.round(n * 10 ** places) / 10 ** places;
const byte = (f) => Math.round(f * 255);
const hex2 = (n) => n.toString(16).padStart(2, "0").toUpperCase();

function color(c) {
  const r = byte(c.r), g = byte(c.g), b = byte(c.b);
  const a = round(c.a ?? 1, 2);
  const hex = `#${hex2(r)}${hex2(g)}${hex2(b)}`;
  return {
    css: a === 1 ? hex : `rgba(${r}, ${g}, ${b}, ${a})`,
    dtcg: { colorSpace: "srgb", components: [round(r / 255, 4), round(g / 255, 4), round(b / 255, 4)], alpha: a, hex },
  };
}

const px = (n) => ({ value: n, unit: "px" });

/** Sets obj[a][b]... = value for a path of segments. */
function put(root, path, value) {
  let node = root;
  for (const key of path.slice(0, -1)) node = node[key] ??= {};
  node[path.at(-1)] = value;
}

function modeValues(variable) {
  const out = {};
  for (const [modeName, entry] of Object.entries(variable.values)) out[modeName.toLowerCase()] = entry;
  return out;
}

export function build(exp) {
  const prim = exp.collections.find((c) => c.name === PRIMITIVES);
  const ui = exp.collections.find((c) => c.name === SEMANTIC);
  if (!prim || !ui) throw new Error(`figma-export.json needs the collections "${PRIMITIVES}" and "${SEMANTIC}".`);
  const modeNames = ui.modes.map((m) => m.name.toLowerCase());
  if (MODES.some((m) => !modeNames.includes(m))) throw new Error(`"${SEMANTIC}" must have the modes Dark and Light, found ${modeNames.join(", ")}.`);

  const byName = (a, b) => a.name.localeCompare(b.name, "en", { numeric: true });
  const primitives = [...prim.variables].sort(byName);
  const semantic = [...ui.variables].sort(byName);
  const textStyles = [...exp.textStyles].sort(byName);
  const effectStyles = [...exp.effectStyles].sort(byName);

  // ---------- tokens.json (DTCG 2025.10) ----------
  const json = {
    $description: `Illigma design tokens, exported from the Figma file "${exp.file}" (${exp.fileKey}). Generated by packages/tokens/scripts/build.mjs. Do not edit by hand.`,
    $extensions: { [EXT]: { modes: [...MODES], defaultMode: "dark", modeValues: `Semantic tokens carry their Dark value in $value and both modes in $extensions["${EXT}"].modes.` } },
  };
  for (const v of primitives) {
    const entry = Object.values(v.values)[0];
    if (v.type !== "COLOR") throw new Error(`Primitive ${v.name} has unsupported type ${v.type}.`);
    put(json, segments(v.name), { $type: "color", $value: color(entry.value).dtcg });
  }
  const tsTokens = {};
  for (const v of semantic) {
    const modes = modeValues(v);
    const cssVar = cssVarName(v.name);
    if (v.type === "COLOR") {
      const dtcgModes = {};
      for (const m of MODES) {
        const e = modes[m];
        if (e.alias && e.aliasCollection !== PRIMITIVES) throw new Error(`${v.name} (${m}) aliases ${e.alias} outside "${PRIMITIVES}".`);
        dtcgModes[m] = e.alias ? ref(e.alias) : color(e.value).dtcg;
      }
      put(json, segments(v.name), { $type: "color", $value: dtcgModes.dark, $extensions: { [EXT]: { modes: dtcgModes, cssVar } } });
      tsTokens[v.name] = {
        type: "color",
        cssVar,
        dark: color(modes.dark.value).css,
        light: color(modes.light.value).css,
        alias: { dark: modes.dark.alias ?? null, light: modes.light.alias ?? null },
      };
    } else if (v.type === "FLOAT") {
      const dtcgModes = { dark: px(modes.dark.value), light: px(modes.light.value) };
      put(json, segments(v.name), { $type: "dimension", $value: dtcgModes.dark, $extensions: { [EXT]: { modes: dtcgModes, cssVar } } });
      tsTokens[v.name] = { type: "dimension", cssVar, dark: modes.dark.value, light: modes.light.value };
    } else {
      throw new Error(`Semantic token ${v.name} has unsupported type ${v.type}.`);
    }
  }

  const tsText = {};
  for (const s of textStyles) {
    if (s.lineHeight.unit !== "PIXELS") throw new Error(`${s.name}: line height must be in pixels.`);
    const weight = s.fontName.variationSettings?.wght ?? FONT_WEIGHTS[s.fontName.style];
    if (!weight) throw new Error(`${s.name}: unknown font style ${s.fontName.style}.`);
    const lsEm = s.letterSpacing.unit === "PERCENT" ? round(s.letterSpacing.value / 100, 4) : round(s.letterSpacing.value / s.fontSize, 4);
    const family = s.fontName.family;
    const cssVar = cssVarName(s.name, "type-");
    put(json, ["typography", ...segments(s.name)], {
      $type: "typography",
      $value: {
        fontFamily: [family, ...(FONT_FALLBACKS[family] ?? DEFAULT_FALLBACK).split(", ")],
        fontWeight: weight,
        fontSize: px(s.fontSize),
        lineHeight: round(s.lineHeight.value / s.fontSize, 4),
        letterSpacing: px(round(lsEm * s.fontSize, 4)),
      },
      ...(s.description ? { $description: s.description } : {}),
      $extensions: { [EXT]: { lineHeightPx: s.lineHeight.value, letterSpacingEm: lsEm, cssVar } },
    });
    tsText[s.name] = {
      cssVar,
      letterSpacingVar: `${cssVar}-letter-spacing`,
      fontFamily: family,
      fontWeight: weight,
      fontSize: s.fontSize,
      lineHeight: s.lineHeight.value,
      letterSpacingEm: lsEm,
      css: `${weight} ${s.fontSize}px/${s.lineHeight.value}px "${family}", ${FONT_FALLBACKS[family] ?? DEFAULT_FALLBACK}`,
    };
  }

  const tsElevation = {};
  for (const s of effectStyles) {
    const shadows = s.effects.filter((e) => e.visible !== false);
    if (shadows.some((e) => e.type !== "DROP_SHADOW" && e.type !== "INNER_SHADOW")) throw new Error(`${s.name}: only shadow effects are supported.`);
    const cssVar = cssVarName(s.name);
    put(json, segments(s.name), {
      $type: "shadow",
      $value: shadows.map((e) => ({
        color: color(e.color).dtcg,
        offsetX: px(e.offset.x),
        offsetY: px(e.offset.y),
        blur: px(e.radius),
        spread: px(e.spread ?? 0),
        ...(e.type === "INNER_SHADOW" ? { inset: true } : {}),
      })),
      $extensions: { [EXT]: { cssVar } },
    });
    tsElevation[s.name] = {
      cssVar,
      css: shadows
        .map((e) => `${e.type === "INNER_SHADOW" ? "inset " : ""}${e.offset.x}px ${e.offset.y}px ${e.radius}px ${e.spread ?? 0}px ${color(e.color).css}`)
        .join(", "),
    };
  }

  // ---------- tokens.css ----------
  const allVars = [
    ...Object.values(tsTokens).map((t) => t.cssVar),
    ...Object.values(tsText).flatMap((t) => [t.cssVar, t.letterSpacingVar]),
    ...Object.values(tsElevation).map((t) => t.cssVar),
  ];
  const dupes = allVars.filter((v, i) => allVars.indexOf(v) !== i);
  if (dupes.length) throw new Error(`Two tokens map to the same CSS variable: ${[...new Set(dupes)].join(", ")}. Rename one in Figma.`);
  const value = (t, m) => (t.type === "color" ? t[m] : `${t[m]}px`);
  const shared = [], themed = [];
  for (const [name, t] of Object.entries(tsTokens)) (value(t, "dark") === value(t, "light") ? shared : themed).push([name, t]);
  const decl = (k, v) => `  ${k}: ${v};`;
  const block = (selector, lines, indent = "") =>
    `${indent}${selector} {\n${lines.map((l) => indent + l).join("\n")}\n${indent}}`;
  const themeLines = (m) => [decl("color-scheme", m), ...themed.map(([, t]) => decl(t.cssVar, value(t, m)))];
  const css = [
    `/* Illigma design tokens. Generated by packages/tokens/scripts/build.mjs from figma-export.json. Do not edit by hand. */`,
    "",
    "/* Same in every mode: dimensions, type styles, elevation, mode-independent colours. */",
    block(":root", [
      ...shared.map(([, t]) => decl(t.cssVar, value(t, "dark"))),
      ...Object.values(tsText).flatMap((t) => [decl(t.cssVar, t.css), decl(t.letterSpacingVar, `${t.letterSpacingEm}em`)]),
      ...Object.values(tsElevation).map((t) => decl(t.cssVar, t.css)),
    ]),
    "",
    "/* Dark is the default theme. */",
    block(':root,\n[data-theme="dark"]', themeLines("dark")),
    "",
    block('[data-theme="light"]', themeLines("light")),
    "",
    "/* Follow the system when no theme is forced. */",
    `@media (prefers-color-scheme: light) {\n${block(':root:not([data-theme="dark"])', themeLines("light"), "  ")}\n}`,
    "",
  ].join("\n");

  // ---------- src/index.ts ----------
  const lit = (o) => JSON.stringify(o, null, 2);
  const ts = `// Illigma design tokens. Generated by packages/tokens/scripts/build.mjs from figma-export.json. Do not edit by hand.

export type Mode = "dark" | "light";

export interface ColorToken {
  readonly type: "color";
  /** CSS custom property defined in tokens.css. */
  readonly cssVar: string;
  /** CSS colour: #RRGGBB, or rgba() when the colour has alpha. */
  readonly dark: string;
  readonly light: string;
  /** The "Illigma Primitives" variable each mode aliases, or null for a raw value. */
  readonly alias: { readonly dark: string | null; readonly light: string | null };
}

export interface DimensionToken {
  readonly type: "dimension";
  readonly cssVar: string;
  /** Pixels. */
  readonly dark: number;
  readonly light: number;
}

export interface TextStyle {
  readonly cssVar: string;
  readonly letterSpacingVar: string;
  readonly fontFamily: string;
  readonly fontWeight: number;
  /** Pixels. */
  readonly fontSize: number;
  /** Pixels. */
  readonly lineHeight: number;
  readonly letterSpacingEm: number;
  /** CSS \`font\` shorthand. */
  readonly css: string;
}

export interface Elevation {
  readonly cssVar: string;
  /** CSS \`box-shadow\` value. */
  readonly css: string;
}

/** Semantic tokens from the "Illigma UI" collection, keyed by their Figma name. */
export const tokens = ${lit(tsTokens)} as const satisfies Record<string, ColorToken | DimensionToken>;

export type TokenName = keyof typeof tokens;

/** Local text styles, keyed by their Figma name. */
export const textStyles = ${lit(tsText)} as const satisfies Record<string, TextStyle>;

export type TextStyleName = keyof typeof textStyles;

/** Local effect styles, keyed by their Figma name. */
export const elevations = ${lit(tsElevation)} as const satisfies Record<string, Elevation>;

export type ElevationName = keyof typeof elevations;
`;

  return { "tokens.json": `${JSON.stringify(json, null, 2)}\n`, "tokens.css": css, "src/index.ts": ts };
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function buildFromDisk() {
  return build(JSON.parse(readFileSync(join(root, "figma-export.json"), "utf8")));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = buildFromDisk();
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [file, content] of Object.entries(files)) {
    const path = join(root, file);
    if (check) {
      let current = "";
      try { current = readFileSync(path, "utf8"); } catch {}
      if (current !== content) { stale = true; console.error(`stale: ${file}`); }
    } else {
      writeFileSync(path, content);
      console.log(`wrote ${file}`);
    }
  }
  if (stale) { console.error("Run npm run build:tokens -w @illigma/tokens."); process.exit(1); }
}
